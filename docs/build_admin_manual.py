def _h(doc: Document, text: str, level: int = 1) -> None:
    doc.add_heading(text, level=level)


def _p(doc: Document, text: str, bold: bool = False) -> None:
    para = doc.add_paragraph()
    run = para.add_run(text)
    run.bold = bold


def _bullet(doc: Document, items: list[str]) -> None:
    for item in items:
        doc.add_paragraph(item, style="List Bullet")


def _numbered(doc: Document, items: list[str]) -> None:
    for item in items:
        doc.add_paragraph(item, style="List Number")


def _screenshot_placeholder(doc: Document, caption: str, instruction: str) -> None:
    """Insert tiny placeholder image + caption. Replace in Word with real PrintScreen."""
    doc.add_paragraph()
    p = doc.add_paragraph()
    p.alignment = WD_ALIGN_PARAGRAPH.CENTER
    try:
        stream = io.BytesIO(_PLACEHOLDER_PNG)
        run = p.add_run()
        run.add_picture(stream, width=Cm(14))
    except Exception:
        p.add_run("[Δεν φορτώθηκε η εικόνα placeholder]")
    cap = doc.add_paragraph()
    cap.alignment = WD_ALIGN_PARAGRAPH.CENTER
    r = cap.add_run(f"Εικόνα: {caption}")
    r.italic = True
    r.font.size = Pt(10)
    note = doc.add_paragraph()
    note.add_run("Πώς να βάλετε πραγματικό στιγμιότυπο: ").bold = True
    note.add_run(instruction)
    doc.add_paragraph()


